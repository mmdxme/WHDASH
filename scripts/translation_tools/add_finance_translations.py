def add_finance_translations():
    """Add finance translations to translations.py"""
    translations_path = 'C:/Users/sdads/WHDASH/translations.py'
    
    with open(translations_path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Find each language section and add translations
    for lang, translations in TRANSLATIONS_TO_ADD.items():
        # Find the section for this language
        # Each language section starts with '    'xx': {'
        pattern = rf"(\s+'{lang}':\s*\{{)"
        
        # Find where the language section ends (the closing brace at the right indentation)
        match = re.search(pattern, content)
        if match:
            start_pos = match.start()
            # Find the section (should be at the beginning of a line with proper indentation)
            # Find the opening brace
            open_pos = content.find('{', start_pos)
            
            # Find the matching closing brace (accounting for nested dicts)
            depth = 1
            pos = open_pos + 1
            while depth > 0 and pos < len(content):
                if content[pos] == '{':
                    depth += 1
                elif content[pos] == '}':
                    depth -= 1
                pos += 1
            
            # Insert translations before the closing brace
            new_translations = []
            for key, value in translations.items():
                # Escape any single quotes in the value
                escaped_value = value.replace("'", "\\'")
                new_translations.append(f"        '{key}': '{escaped_value}',")
            
            new_translations_str = '\n'.join(new_translations) + '\n'
            
            # Insert before the closing brace
            content = content[:pos-1] + '\n' + new_translations_str + content[pos-1:]
            print(f"Added {len(translations)} translations for language: {lang}")
        else:
            print(f"Language section not found: {lang}")
    
    # Write back
    with open(translations_path, 'w', encoding='utf-8') as f:
        f.write(content)
    
    print("Done! Finance translations added.")


if __name__ == '__main__':
    add_finance_translations()
