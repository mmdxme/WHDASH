# RTL languages
RTL_LANGUAGES = ['fa', 'ar']

def get_translation(lang_code, key, default=None):
    """Get translation for a key in specified language."""
    if lang_code not in TRANSLATIONS:
        lang_code = 'en'
    return TRANSLATIONS.get(lang_code, TRANSLATIONS['en']).get(key, default or key)

def get_translations(lang_code):
    """Get all translations for a language."""
    if lang_code not in TRANSLATIONS:
        lang_code = 'en'
    return TRANSLATIONS.get(lang_code, TRANSLATIONS['en'])

def is_rtl(lang_code):
    """Check if language is RTL."""
    return lang_code in RTL_LANGUAGES

def get_language_direction(lang_code):
    """Get direction for a language."""
    lang = next((l for l in LANGUAGES if l['code'] == lang_code), None)
    return lang['direction'] if lang else 'ltr'
