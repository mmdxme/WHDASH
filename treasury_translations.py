def get_treasury_translation(key, language='en'):
    """Get a treasury translation for a given key and language."""
    if language not in TREASURY_TRANSLATIONS:
        language = 'en'
    return TREASURY_TRANSLATIONS.get(language, TREASURY_TRANSLATIONS['en']).get(key, key)


def get_all_treasury_translations(language='en'):
    """Get all treasury translations for a language."""
    if language not in TREASURY_TRANSLATIONS:
        language = 'en'
    return TREASURY_TRANSLATIONS.get(language, TREASURY_TRANSLATIONS['en'])
