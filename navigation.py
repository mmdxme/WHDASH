    from database import get_db_context
    with get_db_context() as db:
        result = db.execute(
            "SELECT COUNT(*) as cnt FROM task_items WHERE assigned_to_user_id = ? AND status NOT IN ('Completed', 'Canceled')",
            (user_id,)
        ).fetchone()
        return result['cnt'] if result else 0


