def get_finance_translation(key, lang='en'):
    """
    Get a finance-specific translation for a given key and language.
    
    Args:
        key: Translation key (e.g., 'journal_entry', 'net_profit')
        lang: Language code (e.g., 'en', 'ar', 'fa')
    
    Returns:
        Translated string, or English fallback if not found
    """
    if lang not in FINANCE_TRANSLATIONS:
        lang = 'en'
    
    translations = FINANCE_TRANSLATIONS.get(lang, FINANCE_TRANSLATIONS['en'])
    return translations.get(key, FINANCE_TRANSLATIONS['en'].get(key, key))


def get_all_finance_translations(lang='en'):
    """
    Get all finance translations for a given language.
    
    Args:
        lang: Language code
    
    Returns:
        Dictionary of all finance translations
    """
    if lang not in FINANCE_TRANSLATIONS:
        lang = 'en'
    return FINANCE_TRANSLATIONS.get(lang, FINANCE_TRANSLATIONS['en'])


def tfinance(key, lang=None):
    """
    Shortcut for get_finance_translation.
    
    Usage:
        {{ tfinance('journal_entry') }}
        {{ tfinance('net_profit', 'ar') }}
    """
    if lang is None:
        from flask import session
        lang = session.get('language', 'en')
    return get_finance_translation(key, lang)


